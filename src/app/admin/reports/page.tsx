import ReportsPanel from "@/components/admin/ReportsPanel";
import { getStaffUser } from "@/lib/auth";
import { formatDateTime } from "@/lib/format";
import { getRecentReports } from "@/lib/reports";

export const dynamic = "force-dynamic";

export default async function ReportsPage() {
  const [staff, recent] = await Promise.all([getStaffUser(), getRecentReports()]);

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-xl font-bold text-slate-900">Reports</h1>
        <p className="mt-1 text-sm text-slate-500">
          Generate NLP error and chatbot performance reports. Export them as
          CSV or PDF.
        </p>
      </div>

      <ReportsPanel staffName={staff?.name ?? "Staff"} />

      <section className="rounded-2xl border border-slate-200 bg-white p-5 shadow-sm print:hidden">
        <h2 className="text-sm font-semibold text-slate-800">
          Recently generated reports
        </h2>
        {recent.length === 0 ? (
          <p className="mt-3 text-sm text-slate-400">
            No reports have been generated yet.
          </p>
        ) : (
          <table className="mt-3 min-w-full divide-y divide-slate-200 text-sm">
            <thead className="bg-slate-50">
              <tr>
                <th className="px-3 py-2 text-left font-semibold text-slate-600">
                  Report type
                </th>
                <th className="px-3 py-2 text-left font-semibold text-slate-600">
                  Period
                </th>
                <th className="px-3 py-2 text-left font-semibold text-slate-600">
                  Generated by
                </th>
                <th className="px-3 py-2 text-left font-semibold text-slate-600">
                  Generated at
                </th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {recent.map((report) => (
                <tr key={report.id}>
                  <td className="px-3 py-2 text-slate-700">
                    {report.report_type}
                  </td>
                  <td className="px-3 py-2 text-slate-600">
                    {report.date_from} to {report.date_to}
                  </td>
                  <td className="px-3 py-2 text-slate-600">
                    {report.generated_by_name}
                  </td>
                  <td className="px-3 py-2 text-slate-500">
                    {formatDateTime(report.generated_at)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </section>
    </div>
  );
}
